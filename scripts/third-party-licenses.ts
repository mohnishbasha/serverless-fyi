/** Regenerates THIRD_PARTY_LICENSES.md from `pnpm licenses list --prod --json`. */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

type Pkg = { name: string; versions: string[]; homepage?: string };
const raw = execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], { encoding: 'utf8' });
// Platform-specific optional binaries differ between macOS and Linux CI; leave them out so the file is stable.
const PLATFORM = /(darwin|linux|win32|android|freebsd|openbsd|sunos|wasm32|musl|gnueabihf|-arm64|-x64|-ia32)/;
const byLicense = Object.fromEntries(
  Object.entries(JSON.parse(raw) as Record<string, Pkg[]>)
    .map(([k, v]) => [k, v.filter((p) => !PLATFORM.test(p.name))] as const)
    .filter(([, v]) => v.length > 0),
);
const lines = [
  '# Third-party licenses',
  '',
  'Production dependencies shipped or used to build the site. Generated by `pnpm licenses:gen`; do not edit by hand.',
  '',
];
for (const license of Object.keys(byLicense).sort()) {
  lines.push(`## ${license}`, '');
  for (const p of [...(byLicense[license] ?? [])].sort((a, b) => a.name.localeCompare(b.name))) {
    lines.push(`- ${p.name} ${p.versions.join(', ')}${p.homepage ? ` — <${p.homepage}>` : ''}`);
  }
  lines.push('');
}
writeFileSync('THIRD_PARTY_LICENSES.md', lines.join('\n'));
console.log(`THIRD_PARTY_LICENSES.md: ${Object.values(byLicense).flat().length} packages`);
