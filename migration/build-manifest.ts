/**
 * Builds migration/legacy-urls.json (append-only), migration/tag-map.json, src/content/tags/*.md
 * stubs, and migration/report.md from the raw export + converted posts.
 */
import { existsSync } from 'node:fs';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { legacyTagSlug } from '../src/lib/tags';
import type { PublicationTag } from './lib/beehiiv';
import { POSTS_DIR, RAW, ROOT, readJson, writeJson } from './lib/io';
import { buildManifest, type ManifestEntry } from './lib/manifest';
import type { PostReport } from './html-to-md';

async function main() {
  const sitemapPaths = await readJson<string[]>(path.join(RAW, 'sitemap-paths.json'));
  const pubTags = await readJson<PublicationTag[]>(path.join(RAW, 'publication-tags.json'));
  const reports = existsSync(path.join(RAW, 'convert-report.json'))
    ? await readJson<PostReport[]>(path.join(RAW, 'convert-report.json'))
    : [];
  const images = existsSync(path.join(RAW, 'images-report.json'))
    ? await readJson<{ downloaded: number }>(path.join(RAW, 'images-report.json'))
    : { downloaded: 0 };

  const postSlugs: string[] = [];
  const postTags = new Set<string>();
  for (const slug of (await readdir(POSTS_DIR)).sort()) {
    const f = path.join(POSTS_DIR, slug, 'index.mdx');
    if (!existsSync(f)) continue;
    postSlugs.push(slug);
    const src = await readFile(f, 'utf8');
    const block = /^tags:\n((?: {2}- .+\n)+)/m.exec(src)?.[1] ?? '';
    for (const m of block.matchAll(/- "?([a-z0-9-]+)"?/g)) if (m[1]) postTags.add(m[1]);
  }
  const allTags = [...new Set([...postTags, ...pubTags.map((t) => t.slug)])].sort();

  const manifestFile = path.join(ROOT, 'migration/legacy-urls.json');
  const previous = existsSync(manifestFile) ? await readJson<ManifestEntry[]>(manifestFile) : [];
  const manifest = buildManifest({ sitemapPaths, postSlugs, tags: allTags, previous });
  await writeJson(manifestFile, manifest);

  const tagMap: Record<string, string> = {};
  for (const t of allTags) {
    const l = legacyTagSlug(t);
    if (l) tagMap[l] = t;
  }
  await writeJson(path.join(ROOT, 'migration/tag-map.json'), tagMap);

  const tagsDir = path.join(ROOT, 'src/content/tags');
  await mkdir(tagsDir, { recursive: true });
  for (const t of allTags) {
    const f = path.join(tagsDir, `${t}.md`);
    if (existsSync(f)) continue;
    const d = pubTags.find((p) => p.slug === t)?.description?.trim();
    await writeFile(f, `---\n${d ? `description: ${JSON.stringify(d)}\n` : ''}---\n`);
  }

  const flaggedDesc = reports.filter((r) => r.descriptionFlagged);
  const overridden = reports.filter((r) => r.tagsOverridden);
  const emptyTags = allTags.filter((t) => !postTags.has(t));
  const sum = (k: keyof PostReport['stats']) => reports.reduce((a, r) => a + r.stats[k], 0);
  const lines = [
    '# Migration report',
    '',
    `Generated by \`pnpm migrate:convert\` on ${new Date().toISOString().slice(0, 10)}. Source: sitemap + embedded post JSON scrape (ADR-013).`,
    '',
    '## Totals',
    '',
    '| Metric | Count |',
    '| --- | --- |',
    `| Posts migrated | ${postSlugs.length} |`,
    `| Images localized (body + covers) | ${images.downloaded} |`,
    `| Embeds converted to components | ${sum('embeds')} |`,
    `| Internal links rewritten | ${sum('internalLinks')} |`,
    `| Links with utm_* stripped | ${sum('utmStripped')} |`,
    `| Code blocks | ${sum('codeBlocks')} |`,
    `| Beehiiv chrome elements removed | ${sum('chromeRemoved')} |`,
    `| Tags | ${allTags.length} |`,
    `| Legacy URL manifest entries | ${manifest.length} (${manifest.filter((e) => e.type === 'redirect').length} redirect stubs) |`,
    `| Posts with \`aeoPending: true\` | ${postSlugs.length} (all migrated posts) |`,
    '',
    '## Owner review needed',
    '',
    `### Descriptions composed from subtitle + verbatim body text (${flaggedDesc.length})`,
    '',
    'Beehiiv meta description was missing, < 70 or > 160 chars. The migrator used the author’s own words only (ADR-018). Rewrite if desired.',
    '',
    ...flaggedDesc.map((r) => `- [ ] \`${r.slug}\``),
    '',
    `### Tags assigned to untagged posts (${overridden.length})`,
    '',
    'Schema requires ≥ 1 tag. Chosen from post content via `migration/tag-overrides.json`.',
    '',
    ...overridden.map((r) => `- [ ] \`${r.slug}\` → ${r.tags.map((t) => `\`${t}\``).join(', ')}`),
    '',
    `### Tags with no posts (${emptyTags.length})`,
    '',
    'These Beehiiv tag URLs are preserved; the pages render with a “no posts yet” note and are `noindex` and excluded from the sitemap.',
    '',
    ...emptyTags.map((t) => `- \`/t/${t}/\``),
    '',
    '### Images with empty alt text',
    '',
    'Beehiiv exported these images with `alt=""` (treated as decorative). Add alt text where the image carries meaning.',
    '',
    ...reports.filter((r) => r.emptyAltImages > 0).map((r) => `- [ ] \`${r.slug}\` — ${r.emptyAltImages}`),
    '',
    '### Cover alt text',
    '',
    'Every migrated cover uses the placeholder alt `Cover image for “<title>”`. Replace with a description of the image.',
    '',
    '### AEO fields',
    '',
    'All migrated posts are `aeoPending: true`: TL;DR, key takeaways and FAQ are hidden and omitted from JSON-LD until the owner writes them.',
    '',
    '## Warnings',
    '',
    ...(reports.flatMap((r) => r.warnings.map((w) => `- \`${r.slug}\`: ${w}`)).length
      ? reports.flatMap((r) => r.warnings.map((w) => `- \`${r.slug}\`: ${w}`))
      : ['None.']),
    '',
  ];
  await writeFile(path.join(ROOT, 'migration/report.md'), lines.join('\n'));
  console.log(`manifest: ${manifest.length} entries · tags: ${allTags.length} · report: migration/report.md`);
}

main().catch((e: unknown) => {
  console.error(e);
  process.exit(1);
});
